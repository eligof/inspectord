def _make_runner(
    outcomes: dict[str, Any],
) -> Callable[..., subprocess.CompletedProcess[str]]:
    """Return a fake runner that dispatches on the first element of *cmd*.

    *outcomes* maps command name (str) to either:
    - a ``subprocess.CompletedProcess`` instance / object with ``.returncode``
      and ``.stdout``, or
    - an exception class/instance to raise.
    """

    def runner(
        cmd: list[str],
        **_kwargs: Any,
    ) -> subprocess.CompletedProcess[str]:
        key = cmd[0]
        outcome = outcomes[key]
        if isinstance(outcome, BaseException) or (
            isinstance(outcome, type) and issubclass(outcome, BaseException)
        ):
            raise outcome
        return outcome  # type: ignore[return-value]

    return runner


def _ok(stdout: str) -> subprocess.CompletedProcess[str]:
    return subprocess.CompletedProcess(args=[], returncode=0, stdout=stdout)


def _fail(stdout: str = "") -> subprocess.CompletedProcess[str]:
    return subprocess.CompletedProcess(args=[], returncode=1, stdout=stdout)


def test_capture_ruleset_nft_success() -> None:
    runner = _make_runner({"nft": _ok("table inet filter {}")})
    backend, text = _capture_ruleset(runner=runner)
    assert backend == "nftables"
    assert text == "table inet filter {}"


def test_capture_ruleset_nft_missing_falls_through_to_iptables() -> None:
    runner = _make_runner(
        {
            "nft": FileNotFoundError("nft not found"),
            "iptables-save": _ok("# Generated by iptables-save\n"),
        }
    )
    backend, _text = _capture_ruleset(runner=runner)
    assert backend == "iptables"


def test_capture_ruleset_both_unavailable_returns_none() -> None:
    runner = _make_runner(
        {
            "nft": FileNotFoundError("nft not found"),
            "iptables-save": FileNotFoundError("iptables-save not found"),
        }
    )
    backend, text = _capture_ruleset(runner=runner)
    assert backend == "none"
    assert text == ""


def test_capture_ruleset_nft_nonzero_falls_through() -> None:
    runner = _make_runner(
        {
            "nft": _fail("error: ..."),
            "iptables-save": _ok("# iptables rules\n"),
        }
    )
    backend, _text = _capture_ruleset(runner=runner)
    assert backend == "iptables"


def test_capture_ruleset_timeout_falls_through() -> None:
    runner = _make_runner(
        {
            "nft": subprocess.TimeoutExpired(cmd=["nft"], timeout=10),
            "iptables-save": _ok("# iptables rules\n"),
        }
    )
    backend, _text = _capture_ruleset(runner=runner)
    assert backend == "iptables"


