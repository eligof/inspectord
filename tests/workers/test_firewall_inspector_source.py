def _make_capture(*snapshots: tuple[str, str]) -> Callable[[], tuple[str, str]]:
    """Return a callable that yields each ``(backend, text)`` tuple in turn."""
    seq = list(snapshots)
    idx = 0

    def capture() -> tuple[str, str]:
        nonlocal idx
        val = seq[idx]
        idx = min(idx + 1, len(seq) - 1)
        return val

    return capture


_NFT_A = ("nftables", "table inet filter {\n  chain input { drop }\n}\n")
_NFT_B = ("nftables", "table inet filter {\n  chain input { accept }\n}\n")
_NONE = ("none", "")
_IPT_A = ("iptables", "# Generated\n-A INPUT -j DROP\n")


def test_source_baseline_not_emitted_on_first_poll() -> None:
    """Ruleset present at construction must NOT appear on the first poll."""
    capture = _make_capture(_NFT_A, _NFT_A)
    src = FirewallSource(capture=capture)
    result = src.poll(timeout_ms=0)
    assert result == []


def test_source_rule_change_emits_record() -> None:
    """A ruleset change after baseline emits one firewall_ruleset_changed record."""
    capture = _make_capture(_NFT_A, _NFT_B)
    src = FirewallSource(capture=capture)
    result = src.poll(timeout_ms=0)
    assert len(result) == 1
    rec = result[0]
    assert rec["action"] == "firewall_ruleset_changed"
    assert rec["backend"] == "nftables"
    assert rec["previous_digest"] == _digest(_NFT_A[1])
    assert rec["digest"] == _digest(_NFT_B[1])
    assert rec["added"] >= 1
    assert rec["removed"] >= 1
    assert isinstance(rec["diff"], str)


def test_source_identical_ruleset_emits_nothing() -> None:
    """No records emitted when the ruleset is unchanged across polls."""
    capture = _make_capture(_NFT_A, _NFT_A, _NFT_A)
    src = FirewallSource(capture=capture)
    assert src.poll(timeout_ms=0) == []
    assert src.poll(timeout_ms=0) == []


def test_source_none_to_readable_emits_nothing() -> None:
    """Transition from no-firewall to readable backend is silently adopted."""
    capture = _make_capture(_NONE, _NFT_A)
    src = FirewallSource(capture=capture)
    result = src.poll(timeout_ms=0)
    assert result == []


def test_source_readable_to_none_emits_nothing() -> None:
    """Transition from readable backend to none is silently adopted."""
    capture = _make_capture(_NFT_A, _NONE)
    src = FirewallSource(capture=capture)
    result = src.poll(timeout_ms=0)
    assert result == []


def test_source_close_is_idempotent() -> None:
    capture = _make_capture(_NFT_A)
    src = FirewallSource(capture=capture)
    assert src._closed is False
    src.close()
    assert src._closed is True
    src.close()  # must not raise
    assert src._closed is True


def test_source_poll_raises_after_close() -> None:
    """poll() must raise RuntimeError after close() has been called."""
    capture = _make_capture(_NFT_A, _NFT_A)
    src = FirewallSource(capture=capture)
    src.close()
    with pytest.raises(RuntimeError, match="closed"):
        src.poll(timeout_ms=0)


def test_source_snapshot_advances_after_change() -> None:
    """After emitting a change, the new snapshot becomes the baseline."""
    capture = _make_capture(_NFT_A, _NFT_B, _NFT_B)
    src = FirewallSource(capture=capture)
    # First poll: change detected
    result1 = src.poll(timeout_ms=0)
    assert len(result1) == 1
    # Second poll: same ruleset as first poll result — no change
    result2 = src.poll(timeout_ms=0)
    assert result2 == []


def test_source_iptables_backend_change_emits_record() -> None:
    """Works with iptables backend too."""
    ipt_b = ("iptables", "# Generated\n-A INPUT -j ACCEPT\n")
    capture = _make_capture(_IPT_A, ipt_b)
    src = FirewallSource(capture=capture)
    result = src.poll(timeout_ms=0)
    assert len(result) == 1
    assert result[0]["backend"] == "iptables"
