"""Tests for the firewall_inspector ruleset diff source.

All tests inject ``runner`` or ``capture`` callables so they never invoke
real subprocesses or require root privileges.
"""

from __future__ import annotations

import subprocess
from collections.abc import Callable
from typing import Any

import pytest

from inspectord.workers.firewall_inspector.source import (
    FirewallSource,
    _capture_ruleset,
    _diff_summary,
    _digest,
)

# ---------------------------------------------------------------------------
# _digest
# ---------------------------------------------------------------------------

_TEXT_A = "table inet filter {\n  chain input { drop }\n}\n"
_TEXT_B = "table inet filter {\n  chain input { accept }\n}\n"


def test_digest_same_text_same_result() -> None:
    assert _digest(_TEXT_A) == _digest(_TEXT_A)


def test_digest_different_text_different_result() -> None:
    assert _digest(_TEXT_A) != _digest(_TEXT_B)


def test_digest_empty_string_is_stable() -> None:
    assert _digest("") == _digest("")


# ---------------------------------------------------------------------------
# _diff_summary
# ---------------------------------------------------------------------------

_OLD_RULES = "table inet filter {\n  chain input { drop }\n}\n"
_NEW_RULES = "table inet filter {\n  chain input { accept }\n  chain forward { drop }\n}\n"


def test_diff_summary_counts_added_and_removed() -> None:
    result = _diff_summary(_OLD_RULES, _NEW_RULES)
    # "drop" line is removed, "accept" and "chain forward { drop }" are added
    assert result["removed"] >= 1
    assert result["added"] >= 1
    assert isinstance(result["diff"], str)
    assert len(result["diff"]) > 0


def test_diff_summary_identical_texts() -> None:
    result = _diff_summary(_OLD_RULES, _OLD_RULES)
    assert result["added"] == 0
    assert result["removed"] == 0
    assert result["diff"] == ""


def test_diff_summary_truncates_at_max_lines() -> None:
    # Build old/new texts that produce a diff longer than max_lines=5.
    old_lines = [f"rule {i} drop" for i in range(20)]
    new_lines = [f"rule {i} accept" for i in range(20)]
    old = "\n".join(old_lines)
    new = "\n".join(new_lines)
    result = _diff_summary(old, new, max_lines=5)
    assert result["diff"].endswith("… (truncated)")
    # The diff text should have exactly 6 lines (5 content + truncation marker).
    assert len(result["diff"].splitlines()) == 6


def test_diff_summary_no_truncation_when_within_limit() -> None:
    result = _diff_summary(_OLD_RULES, _NEW_RULES, max_lines=200)
    assert "… (truncated)" not in result["diff"]


